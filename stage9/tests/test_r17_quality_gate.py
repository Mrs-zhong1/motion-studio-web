"""R17 evidence-based release gate, not a fabricated aesthetic rating.

All calculations come from actual Chromium screenshot geometry and the real
source manifest generated by test_template_visual_audit.py.  Commercial
licensing, native phone performance, and human visual design are always HOLD.
"""
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/"TEMPLATE_VISUAL_AUDIT.json"
OUTPUT=ROOT/"R17_QUALITY_GATE.json"
IDS={"editorial","product-3d","cinematic","architecture","agency","fashion","gallery","saas"}

def run():
    report=json.loads(SOURCE.read_text())
    rows=report.get("templates",[])
    errors=[]
    if report.get("status")!="pass" or len(rows)!=16:
        errors.append("eight-template × two-viewport prior visual audit did not pass")
    observed={(r.get("template"),r.get("device")) for r in rows}
    if observed!={(t,d) for t in IDS for d in ("desktop","mobile")}:
        errors.append("missing or duplicated template/viewport pair")
    sources={}
    proof=[]
    for row in rows:
        template,viewport=row.get("template"),row.get("device")
        chapters=row.get("sectionCount",0)
        photos=row.get("realPhotoCount",-1)
        fallback=row.get("originalFallbackCount",-1)
        overflow=max(0,row.get("documentWidth",99999)-row.get("viewportWidth",0))
        hashes=[row.get(k) for k in ("firstSectionPngSHA256","chapter3PngSHA256","designedEndingPngSHA256")]
        if chapters not in (4,5) or photos!=chapters or fallback!=0:
            errors.append(f"{template}/{viewport}: real photo coverage is incomplete: {photos}/{chapters} fallback={fallback}")
        if overflow>32 or row.get("collapsedSections",1)>0:
            errors.append(f"{template}/{viewport}: overflow={overflow}px or collapsed section")
        if len(set(hashes))!=3 or not all(h and len(h)==16 for h in hashes):
            errors.append(f"{template}/{viewport}: opening/middle/ending screenshots are not three distinct captured scenes")
        manifest=row.get("sourceManifest",[])
        urls=[entry.get("source") for entry in manifest]
        if len(urls)!=chapters or any(not isinstance(u,str) or not (u.startswith("https://images.unsplash.com/photo-") or u.startswith("ai-generated://")) for u in urls):
            errors.append(f"{template}/{viewport}: missing upstream photograph traceability")
        elif len(set(urls))!=chapters:
            errors.append(f"{template}/{viewport}: photograph URLs repeat within a story")
        if viewport=="desktop":
            sources[template]=urls
        proof.append({"template":template,"viewport":viewport,"chapters":chapters,
            "loadedPhotos":photos,"fallbacks":fallback,"horizontalOverflowPx":overflow,
            "captureHashes":hashes,"commercialRightsApproved":False})
    all_urls=[u for block in sources.values() for u in block]
    if len(all_urls)!=39 or len(set(all_urls))!=39:
        errors.append(f"39 distinct chapter photos required, found {len(all_urls)} total / {len(set(all_urls))} distinct")
    output={"schema":"motion-studio-r17-quality-gate-v1",
       "automatedGate":"FAIL" if errors else "PASS",
       "visualEvidence":"Eight complete templates, desktop/mobile, opening/middle/ending captures",
       "photoCoverage":f"{len(all_urls)}/39",
       "uniquePhotoSourceCount":len(set(all_urls)),
       "geometryAndImageEvidence":proof,
       "blockingErrors":errors,
       "humanVisualArtDirection":"HOLD",
       "nativeMobileGpuPerformance":"HOLD",
       "commercialImageRights":"HOLD",
       "productionRelease":"HOLD",
       "limitations":"Browser automation confirms structural and media evidence, not reference-grade design quality, legal clearance or native-device frame rates."}
    OUTPUT.write_text(json.dumps(output,indent=2,ensure_ascii=False)+"\n")
    if errors:raise AssertionError("\n".join(errors))
    print("R17 AUTOMATED VISUAL GATE PASS — 8 templates × 2 viewports; all 39 photo sources; 48 distinct story screenshots")
    print("R17 HUMAN VISUAL, NATIVE GPU AND COMMERCIAL RIGHTS: HOLD")

if __name__=="__main__":
    run()
