"""R50 browser acceptance for the real Agency and SaaS standalone HTML exports.

This is a rendering/interaction evidence gate, not subjective art-direction approval.
It captures desktop/mobile full-page views plus all five rendered chapter iframes per viewport, and verifies the actual exported runtime.
"""
from functools import partial
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
import hashlib, json, os, threading, traceback

from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[1]
EDITOR = ROOT / "Motion-Studio-Stage15-Meshopt-OFFLINE.html"
OUT = ROOT / "R50_HTML_BROWSER_ACCEPTANCE.json"
SHOTS = Path(os.environ.get("R50_SCREENSHOT_DIR", "/tmp/r50-html-browser"))
TEMPLATES = ("agency", "saas")
report = {
    "schema": "r50-real-html-browser-acceptance-v1",
    "status": "RUNNING",
    "source": EDITOR.name,
    "templates": {},
    "screenshots": [],
    "pageScreenshots": [],
    "errors": [],
    "iframeCaptureStrategy": "direct-srcdoc-document-capture-with-full-page-composite",
    "scope": "actual standalone HTML generated by exportDocument()",
    "humanVisualApproval": "NOT_GRANTED_BY_AUTOMATION",
    "productionEligible": False,
}
server = None

def capture(page, template, viewport, moment):
    SHOTS.mkdir(parents=True, exist_ok=True)
    path = SHOTS / f"{template}-{viewport}-{moment}.png"
    page.screenshot(path=str(path), full_page=False, animations="disabled", timeout=90000)
    raw = path.read_bytes()
    assert raw[:8] == bytes.fromhex("89504e470d0a1a0a"), f"Screenshot is not a valid PNG: {path}"
    assert len(raw) > 1000, f"Screenshot unexpectedly empty: {path} ({len(raw)} bytes)"
    report["screenshots"].append({
        "file": path.name, "bytes": len(raw),
        "sha256": hashlib.sha256(raw).hexdigest(),
        "viewport": viewport, "template": template, "moment": moment,
    })

try:
    assert EDITOR.is_file(), f"Built standalone editor missing: {EDITOR}"
    server = ThreadingHTTPServer(("127.0.0.1", 0),
        partial(SimpleHTTPRequestHandler, directory=str(ROOT)))
    threading.Thread(target=server.serve_forever, daemon=True).start()
    with sync_playwright() as pw:
        browser = pw.chromium.launch(headless=True, args=[
            "--no-sandbox", "--use-gl=angle", "--use-angle=swiftshader",
            "--enable-webgl", "--enable-unsafe-swiftshader",
        ])
        for template in TEMPLATES:
            editor = browser.new_page(viewport={"width": 1440, "height": 900})
            editor_errors = []
            editor.on("pageerror", lambda e: editor_errors.append(str(e)))
            editor.goto(f"http://127.0.0.1:{server.server_port}/{EDITOR.name}",
                        wait_until="domcontentloaded", timeout=30000)
            editor.locator("#discoveryView").wait_for(state="visible", timeout=20000)
            assert editor.locator("[data-template-card]").count() == 8
            editor.locator(f"[data-template-card='{template}']").click()
            editor.locator("#previewUse").click()
            editor.locator("#editorView").wait_for(state="visible")
            assert editor.evaluate("project.templateId") == template
            html = editor.evaluate("exportDocument()")
            assert isinstance(html, str) and len(html) > 30000
            assert 'id="r45-export-composition"' in html
            assert 'id="r46-export-accessibility"' in html
            assert 'id="r43-export-runtime"' in html
            assert 'data-r43-template="' + template + '"' in html

            template_result = {"exportBytes": len(html), "viewports": {},
                               "editorErrors": editor_errors, "exportErrors": []}
            report["templates"][template] = template_result
            for viewport, width, height in (("desktop", 1440, 900), ("mobile", 390, 844)):
                page = browser.new_page(viewport={"width": width, "height": height},
                                        device_scale_factor=1)
                errors = []
                page.on("pageerror", lambda e: errors.append(str(e)))
                page.set_content(html, wait_until="domcontentloaded", timeout=30000)
                # Each chapter is a sandboxed srcdoc iframe. The parent document's
                # image/font readiness does not imply these child documents have rendered.
                iframe_audit = []
                frame_screenshots = []
                for frame_index, child in enumerate(page.frames):
                    if child.parent_frame is None:
                        continue
                    child_result = {"name": child.name, "url": child.url, "loadState": "unknown"}
                    try:
                        child.wait_for_load_state("domcontentloaded", timeout=15000)
                        child_result["loadState"] = "domcontentloaded"
                        child.evaluate("document.fonts.ready")
                        child_result["document"] = child.evaluate("""() => ({
                            readyState: document.readyState,
                            title: document.title,
                            textLength: (document.body?.innerText || '').trim().length,
                            bodyChildCount: document.body?.children.length || 0,
                            background: document.body ? getComputedStyle(document.body).backgroundColor : null,
                            images: Array.from(document.images).map(img => ({
                                complete: img.complete, naturalWidth: img.naturalWidth,
                                naturalHeight: img.naturalHeight
                            })),
                            canvases: Array.from(document.querySelectorAll('canvas')).map(canvas => ({
                                width: canvas.width, height: canvas.height
                            })),
                            visibleElements: Array.from(document.body?.querySelectorAll('*') || [])
                                .filter(el => {
                                    const r = el.getBoundingClientRect(), s = getComputedStyle(el);
                                    return r.width > 8 && r.height > 8 && s.display !== 'none' &&
                                        s.visibility !== 'hidden' && Number(s.opacity) > 0;
                                }).length
                        })""")
                    except Exception as error:
                        child_result["error"] = str(error)
                    iframe_audit.append(child_result)
                template_result.setdefault("iframeAudit", {})[viewport] = iframe_audit
                page.wait_for_timeout(500)
                # Exported scenes embed generated media and may decode asynchronously.
                # Avoid capturing the initial black/loading frame.
                page.evaluate("document.fonts.ready")
                page.wait_for_function("""() => Array.from(document.images).every(
                    image => image.complete && image.naturalWidth > 0
                )""", timeout=20000)
                page.wait_for_timeout(1200)
                media_audit = page.evaluate("""() => ({
                    images: Array.from(document.images).map(image => ({
                        src: image.currentSrc || image.src,
                        complete: image.complete,
                        naturalWidth: image.naturalWidth,
                        naturalHeight: image.naturalHeight
                    })),
                    failedImages: Array.from(document.images)
                        .filter(image => !image.complete || image.naturalWidth === 0)
                        .map(image => image.currentSrc || image.src),
                    canvas: Array.from(document.querySelectorAll('canvas')).map(canvas => ({
                        width: canvas.width, height: canvas.height,
                        cssWidth: Math.round(canvas.getBoundingClientRect().width),
                        cssHeight: Math.round(canvas.getBoundingClientRect().height)
                    })),
                    sectionAudit: Array.from(document.querySelectorAll('.page .section')).map((section, index) => {
                        const box = element => {
                            const r = element.getBoundingClientRect(), s = getComputedStyle(element);
                            return {
                                tag: element.tagName.toLowerCase(),
                                className: typeof element.className === 'string' ? element.className : '',
                                role: element.getAttribute('role'),
                                rect: { x: Math.round(r.x), y: Math.round(r.y),
                                    width: Math.round(r.width), height: Math.round(r.height) },
                                display: s.display, visibility: s.visibility, opacity: s.opacity,
                                background: s.backgroundColor, backgroundImage: s.backgroundImage,
                                color: s.color,
                                text: (element.innerText || element.getAttribute('aria-label') || '').trim().slice(0, 180),
                                src: element.currentSrc || element.getAttribute('src') || null,
                                childCount: element.children.length
                            };
                        };
                        return {
                            index,
                            heading: section.querySelector('.designed-chapter-heading')?.innerText?.trim() || '',
                            section: box(section),
                            media: Array.from(section.querySelectorAll(
                                '.section-art, img, picture, video, canvas, iframe, [class*="media"], [class*="visual"], [class*="art"]'
                            )).map(box),
                            largeVisibleElements: Array.from(section.querySelectorAll('*')).filter(element => {
                                const r = element.getBoundingClientRect(), s = getComputedStyle(element);
                                return r.width >= 100 && r.height >= 100 && s.display !== 'none' &&
                                    s.visibility !== 'hidden' && Number(s.opacity) > 0;
                            }).slice(0, 30).map(box)
                        };
                    }),
                    frames: Array.from(document.querySelectorAll('.page .section iframe')).map((frame, index) => {
                        const rect = frame.getBoundingClientRect();
                        const style = getComputedStyle(frame);
                        let inner = null;
                        try {
                            const doc = frame.contentDocument;
                            const body = doc && doc.body;
                            inner = body ? {
                                readyState: doc.readyState,
                                textLength: (body.innerText || '').trim().length,
                                childCount: body.children.length,
                                images: Array.from(body.querySelectorAll('img')).map(img => ({
                                    src: img.currentSrc || img.src,
                                    complete: img.complete,
                                    naturalWidth: img.naturalWidth,
                                    naturalHeight: img.naturalHeight
                                })),
                                canvases: Array.from(body.querySelectorAll('canvas')).map(canvas => ({
                                    width: canvas.width, height: canvas.height
                                })),
                                background: getComputedStyle(body).backgroundColor
                            } : null;
                        } catch (error) {
                            inner = { crossOriginOrUnreadable: String(error) };
                        }
                        return {
                            index, title: frame.title, src: frame.getAttribute('src'),
                            srcdocBytes: (frame.getAttribute('srcdoc') || '').length,
                            readyState: frame.contentDocument?.readyState || 'unreadable',
                            rect: { x: Math.round(rect.x), y: Math.round(rect.y),
                                width: Math.round(rect.width), height: Math.round(rect.height) },
                            display: style.display, visibility: style.visibility,
                            opacity: style.opacity, background: style.backgroundColor,
                            inner
                        };
                    })
                })""")
                assert not media_audit["failedImages"], (
                    template, viewport, "exported media failed to load", media_audit["failedImages"]
                )
                template_result.setdefault("mediaAudit", {})[viewport] = media_audit

                # Capture each sandboxed srcdoc frame from its own document context.
                # Chromium full-page compositor screenshots can omit nested iframe pixels;
                # cropping those pixels produced valid PNGs containing only the iframe's
                # dark fallback background. Direct child-document captures are the source
                # of truth, then are composited into the full-page layout screenshot.
                frame_documents = [frame for frame in page.frames if frame.parent_frame is not None]
                assert len(frame_documents) == 5, (
                    "expected five exported chapter iframe documents", template, viewport,
                    len(frame_documents)
                )
                captured_frames = []
                for frame_index, child in enumerate(frame_documents):
                    child.wait_for_load_state("domcontentloaded", timeout=15000)
                    child.evaluate("document.fonts.ready")
                    child.wait_for_timeout(700)
                    # Freeze the rendered moment only after the scene has had time to appear.
                    # Fix the child viewport box so animated descendants cannot keep the body
                    # bounding box unstable during Playwright's screenshot actionability check.
                    child.evaluate("""() => {
                        const style = document.createElement('style');
                        style.textContent = 'html,body{width:100%!important;height:100%!important;min-height:100%!important;overflow:hidden!important;scroll-behavior:auto!important}*,*::before,*::after{animation-play-state:paused!important;transition:none!important}';
                        document.head.appendChild(style);
                        document.getAnimations({subtree:true}).forEach(animation => animation.pause());
                    }""")
                    child.wait_for_timeout(100)
                    frame_path = SHOTS / f"{template}-{viewport}-frame-{frame_index + 1:02d}.png"
                    child.locator("body").screenshot(
                        path=str(frame_path), animations="disabled", timeout=90000
                    )
                    frame_raw = frame_path.read_bytes()
                    assert frame_raw[:8] == bytes.fromhex("89504e470d0a1a0a"), (
                        "chapter iframe screenshot is not a PNG", template, viewport, frame_index
                    )
                    assert len(frame_raw) > 1000, (
                        "chapter iframe screenshot is unexpectedly empty", template, viewport,
                        frame_index, len(frame_raw)
                    )
                    from PIL import Image, ImageStat
                    with Image.open(frame_path) as rendered_image:
                        rendered_image.load()
                        rgb = rendered_image.convert("RGB")
                        color_count = len(rgb.getcolors(maxcolors=1000000) or [])
                        color_spread = max(ImageStat.Stat(rgb).stddev)
                    assert color_count >= 24 and color_spread >= 2.5, (
                        "chapter screenshot appears visually blank/monochrome",
                        template, viewport, frame_index, color_count, color_spread
                    )
                    captured_frames.append({
                        "frameIndex": frame_index,
                        "title": child.title(),
                        "file": frame_path.name,
                        "bytes": len(frame_raw),
                        "sha256": hashlib.sha256(frame_raw).hexdigest(),
                        "nonEmpty": True,
                        "captureStrategy": "direct-srcdoc-body-screenshot",
                        "documentTextLength": len(child.locator("body").inner_text().strip()),
                        "uniqueColorCount": color_count,
                        "maxChannelStdDev": round(color_spread, 2),
                    })
                template_result.setdefault("frameScreenshots", {})[viewport] = captured_frames

                # Preserve the real full-page layout, then replace compositor-missing
                # iframe rectangles with the separately captured rendered child documents.
                raw_page_path = SHOTS / f"{template}-{viewport}-parent-raw.png"
                page.screenshot(path=str(raw_page_path), full_page=True,
                                animations="disabled", timeout=90000)
                from PIL import Image
                with Image.open(raw_page_path) as raw_page:
                    raw_page.load()
                    composed = raw_page.convert("RGB")
                    iframe_elements = page.locator(".page .section iframe").all()
                    assert len(iframe_elements) == len(captured_frames) == 5
                    for frame_index, (frame_element, frame_record) in enumerate(zip(iframe_elements, captured_frames)):
                        rect = frame_element.evaluate("""el => {
                            const r = el.getBoundingClientRect();
                            return {x: r.x, y: r.y + window.scrollY,
                                    width: r.width, height: r.height};
                        }""")
                        left, top = round(rect["x"]), round(rect["y"])
                        width, height = round(rect["width"]), round(rect["height"])
                        assert left >= 0 and top >= 0 and left + width <= composed.width and top + height <= composed.height, (
                            "iframe rectangle outside full-page capture", template, viewport,
                            frame_index, rect, composed.size
                        )
                        with Image.open(SHOTS / frame_record["file"]) as frame_image:
                            frame_image.load()
                            rendered = frame_image.convert("RGB")
                            if rendered.size != (width, height):
                                rendered = rendered.resize((width, height), Image.Resampling.LANCZOS)
                            composed.paste(rendered, (left, top))
                    composite_path = SHOTS / f"{template}-{viewport}-all-chapters.png"
                    composed.save(composite_path, format="PNG", optimize=True)
                    composite_raw = composite_path.read_bytes()
                    report["pageScreenshots"].append({
                        "file": composite_path.name,
                        "bytes": len(composite_raw),
                        "sha256": hashlib.sha256(composite_raw).hexdigest(),
                        "template": template,
                        "viewport": viewport,
                        "captureStrategy": "full-page-parent-layout-plus-direct-srcdoc-composites",
                    })
                raw_page_path.unlink()

                geometry = page.evaluate("""() => ({
                    width: document.documentElement.scrollWidth,
                    viewport: innerWidth,
                    height: document.documentElement.scrollHeight
                })""")
                assert geometry["width"] <= geometry["viewport"] + 2, (
                    template, viewport, "horizontal overflow", geometry
                )

                if template == "agency":
                    index = page.locator(".r43-agency-index")
                    index.wait_for(state="visible", timeout=10000)
                    buttons = index.locator("button")
                    count = buttons.count()
                    assert count >= 4, f"Agency project index too small: {count}"
                    capture(page, template, viewport, "opening")
                    buttons.nth(1).click()
                    page.wait_for_timeout(250)
                    assert buttons.nth(1).get_attribute("aria-pressed") == "true"
                    assert page.evaluate("scrollY") > 0, "Agency case index did not navigate"
                    capture(page, template, viewport, "case-navigation")
                    if viewport == "mobile":
                        cols = page.locator(".r43-agency-index").evaluate(
                            "e => getComputedStyle(e).gridTemplateColumns.split(' ').length"
                        )
                        assert cols == 2, f"Agency mobile index is not two columns: {cols}"
                    template_result["viewports"][viewport] = {
                        "sectionCount": page.locator(".page .section").count(),
                        "projectIndexItems": count,
                        "caseNavigation": "PASS",
                        "horizontalOverflow": max(0, geometry["width"]-geometry["viewport"]),
                    }
                else:
                    shell = page.locator(".r43-saas-shell")
                    shell.wait_for(state="visible", timeout=10000)
                    capture(page, template, viewport, "opening")
                    tabs = page.get_by_role("tab")
                    assert tabs.count() == 3
                    title = page.locator(".r43-saas-copy h2")
                    states = []
                    for i, expected in enumerate(("Bring every signal", "Turn raw input", "Move from decision")):
                        tabs.nth(i).click()
                        assert expected in title.inner_text(), (i, title.inner_text())
                        assert tabs.nth(i).get_attribute("aria-selected") == "true"
                        states.append(title.inner_text())
                        capture(page, template, viewport, ("capture", "shape", "deliver")[i])
                    if viewport == "mobile":
                        layout = page.locator(".r43-saas-workflow").evaluate(
                            "e => getComputedStyle(e).flexDirection"
                        )
                        assert layout == "column", f"SaaS mobile workflow not vertical: {layout}"
                        targets = tabs.evaluate_all(
                            "els => els.map(e => Math.round(e.getBoundingClientRect().height))"
                        )
                        assert min(targets) >= 44, f"SaaS mobile touch target below 44px: {targets}"
                    template_result["viewports"][viewport] = {
                        "workflowSteps": len(states), "states": states,
                        "workflowInteraction": "PASS",
                        "horizontalOverflow": max(0, geometry["width"]-geometry["viewport"]),
                    }
                assert not errors, f"{template}/{viewport} browser errors: {errors}"
                template_result["exportErrors"].extend(errors)
                page.close()
            assert not editor_errors, f"{template} editor errors: {editor_errors}"
            report["templates"][template] = template_result
            editor.close()
        browser.close()
    assert set(report["templates"]) == set(TEMPLATES)
    assert len(report["screenshots"]) == 12
    assert len(report["pageScreenshots"]) == 4
    for template in TEMPLATES:
        for viewport in ("desktop", "mobile"):
            frames = report["templates"][template]["frameScreenshots"][viewport]
            assert len(frames) == 5 and all(frame.get("nonEmpty") for frame in frames), (
                "incomplete chapter screenshot evidence", template, viewport, frames
            )
    report["chapterScreenshotCount"] = sum(
        len(viewports) for row in report["templates"].values()
        for viewports in row.get("frameScreenshots", {}).values()
    )
    report["status"] = "PASS_BROWSER_FUNCTIONALITY_ONLY"
except Exception:
    report["status"] = "FAIL"
    report["errors"].append(traceback.format_exc(limit=10))
finally:
    if server:
        server.shutdown()
        server.server_close()
    OUT.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False, indent=2))

assert report["status"] == "PASS_BROWSER_FUNCTIONALITY_ONLY", "R50 real HTML browser acceptance failed"
